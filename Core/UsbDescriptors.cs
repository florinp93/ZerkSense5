    public static readonly byte[] HidReportDs = BuildDs();

    static byte[] BuildDs()
    {
        var d = new List<byte>(HidReportInput);
        d.AddRange([0x85, 0x02, 0x09, 0x23, 0x95, 0x2F, 0x91, 0x02]);
        (byte id, byte usage, byte count)[] features =
        [
            (0x05, 0x33, 0x28), (0x08, 0x34, 0x2F), (0x09, 0x24, 0x13), (0x0A, 0x25, 0x1A),
