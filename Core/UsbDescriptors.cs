    public static byte[] String(int index, bool dse)
    {
        if (index == 0) return [0x04, 0x03, 0x09, 0x04];
        string? s = index switch
        {
            1 => "Sony Interactive Entertainment",
            2 => dse ? "DualSense Edge Wireless Controller" : "DualSense Wireless Controller",
            _ => null,
        };
        if (s == null) return [];
        byte[] utf16 = Encoding.Unicode.GetBytes(s);
        var d = new byte[2 + utf16.Length];
        d[0] = (byte)d.Length;
        d[1] = 0x03;
        utf16.CopyTo(d, 2);
        return d;
    }

